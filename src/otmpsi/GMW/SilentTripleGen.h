class SilentTripleGen {
 public:
  SilentTripleGen();
  ~SilentTripleGen();
  SilentTripleGen(SilentTripleGen&&) noexcept;
  SilentTripleGen& operator=(SilentTripleGen&&) noexcept;
  SilentTripleGen(const SilentTripleGen&) = delete;
  SilentTripleGen& operator=(const SilentTripleGen&) = delete;

  void init(u64 n, u64 batchSize, u64 numThreads, Mode mode, block seed);
  void setTimer(oc::Timer& timer);

  // Retain only the low byte of a disjoint random-OT range generated by the
  // next expand(). This lets callers share one Silent-OT expansion between
  // block triples and short-message protocols without storing all OT blocks.
  // The retained coordinates must never also be consumed as triples.
  void retainByteRandomOts(u64 offset, u64 count);
  RetainedByteOtSender takeRetainedByteOtSender();
  RetainedByteOtReceiver takeRetainedByteOtReceiver();

#ifndef LIBOTE_HAS_STATIONARY_SILENT_OT
  RequiredBase requiredBaseOts();

  void setBaseOts(span<block> recvOts, span<std::array<block, 2>> sendOts);
#endif

  Proto expand(coproto::Socket& chl);

  bool hasBaseOts() const;

  Proto generateBaseOts(u64 partyIdx, coproto::Socket& chl);

  block* multData();
  u64 multSize() const;
  block* addData();
  u64 addSize() const;

 private:
  struct Impl;
  std::unique_ptr<Impl> mImpl;
};

